def _norm(v: str | None) -> str:
    return (v or "").strip().replace("ي", "ی").replace("ك", "ک")


def suggest_structure(name: str | None = None, category: str | None = None,
                      component_type: str | None = None,
                      model: str | None = None) -> dict[str, Any]:
    """§3B — suggest subsystems/components for an equipment being defined."""
    ct = _norm(component_type)
    nm = _norm(name)
    cat = _norm(category)

    if ct in STRUCTURE_KB:
        kb, basis = STRUCTURE_KB[ct], f"نوع قطعه «{ct}»"
    else:
        matched = None
        for key in STRUCTURE_KB:
            if key and (key in nm or key in ct):
                matched = key
                break
        if matched:
            kb, basis = STRUCTURE_KB[matched], f"تشخیص «{matched}» از نام/نوع تجهیز"
        elif cat in CATEGORY_KB:
            kb, basis = CATEGORY_KB[cat], f"دسته «{cat}»"
        else:
            kb, basis = GENERIC_STRUCTURE, "الگوی عمومی (نوع تجهیز نامشخص)"

    return {
        "basis": basis,
        "subsystems": [
            {"name": s["نام"], "components": list(s["قطعات"])} for s in kb
        ],
        "note": "SELEN فقط پیشنهاد می‌دهد؛ هیچ آیتمی بدون کلیک کاربر روی «+» اضافه نمی‌شود (§14)",
    }


def suggest_checklist_items(name: str | None = None, category: str | None = None,
                            component_type: str | None = None) -> dict[str, Any]:
    """§5B — suggest inspection items for a checklist template."""
    ct = _norm(component_type)
    nm = _norm(name)

    if ct in CHECKLIST_KB:
        items, basis = CHECKLIST_KB[ct], f"نوع قطعه «{ct}»"
    else:
        matched = next((k for k in CHECKLIST_KB if k and (k in nm or k in ct)), None)
        if matched:
            items, basis = CHECKLIST_KB[matched], f"تشخیص «{matched}» از نام/نوع"
        else:
            items, basis = GENERIC_CHECKLIST, "الگوی عمومی بازرسی"

    return {
        "basis": basis,
        "items": list(items),
        "note": "SELEN فقط پیشنهاد می‌دهد؛ آیتم‌ها با کلیک «+» به فرم اضافه می‌شوند (§14)",
    }
